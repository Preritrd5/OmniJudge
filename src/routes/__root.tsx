export const Route = createRootRouteWithContext<{ queryClient: QueryClient }>()({
  head: () => ({
    meta: [
      { charSet: "utf-8" },
      { name: "viewport", content: "width=device-width, initial-scale=1" },
      { title: "SIH Premier 2026 — Submission & Evaluation Platform" },
      { name: "description", content: "Official submission and evaluation portal for SIH Premier 2026." },
      { name: "author", content: "SIH Premier 2026" },
      { property: "og:title", content: "SIH Premier 2026" },
      { property: "og:description", content: "Official submission and evaluation portal for SIH Premier 2026." },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary" },
    ],
    links: [
      {
        rel: "stylesheet",
        href: appCss,
      },
    ],
  }),
  shellComponent: RootShell,
  component: RootComponent,
  notFoundComponent: NotFoundComponent,
  errorComponent: ErrorComponent,
});

function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
        {/* Inline script: apply saved theme before first paint to avoid flash */}
        <script
          dangerouslySetInnerHTML={{
            __html: `(function(){var t=localStorage.getItem('theme')||'dark';document.documentElement.classList.toggle('light-mode',t==='light');document.documentElement.classList.toggle('dark',t==='dark');})();`,
          }}
        />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    const unsubscribe = subscribeAuthSync((event) => {
      if (event.type === "ADMIN_AUTH_CHANGED" && event.event === "SIGNED_OUT") {
        queryClient.cancelQueries().then(() => {
          queryClient.clear();
          router.invalidate();
        });
      }
    });
    return () => unsubscribe();
  }, [queryClient, router]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
    </QueryClientProvider>
  );
}
